use std::ops::Range;

#[derive(Clone, Debug, PartialEq)]
pub enum TokenKind {
    Fn,
    Let,
    Mut,
    If,
    Elif,
    Else,
    For,
    While,
    In,
    Return,
    I64,
    F64,
    Bool,
    Str,
    Unit,
    True,
    False,
    Println,
    Struct,
    Enum,
    Ident(String),
    Integer(i64),
    Float(f64),
    StrLit(String),
    Plus,
    Minus,
    Star,
    Slash,
    Percent,
    Assign,
    PlusAssign,
    MinusAssign,
    StarAssign,
    SlashAssign,
    EqEq,
    NotEq,
    Lt,
    Gt,
    LtEq,
    GtEq,
    And,
    Or,
    Bang,
    DotDot,
    DotDotEllipsis,
    Dot,
    DoubleColon,
    LParen,
    RParen,
    LBrace,
    RBrace,
    Comma,
    Colon,
    RArrow,
    Error,
    Eof,
}

#[derive(Clone, Debug, PartialEq)]
pub struct Token {
    pub kind: TokenKind,
    pub span: Range<usize>,
}
